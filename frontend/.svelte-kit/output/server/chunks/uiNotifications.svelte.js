function showToast(message, type = "info") {
	const id = `toast-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`;
	toasts = [...toasts, {
		id,
		type,
		message
	}];
	setTimeout(() => {
		removeToast(id);
	}, 4e3);
}
function removeToast(id) {
	toasts = toasts.filter((toast) => toast.id !== id);
}
